-- PROPOSAL ONLY. Run once as local postgres against the new disposable database.
-- All fixture relations, identity sequences, and foreign keys stay in this DB.
\set ON_ERROR_STOP on
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $$
BEGIN
    IF inet_server_addr() IS DISTINCT FROM '127.0.0.1'::inet
       OR inet_server_port() IS DISTINCT FROM 55432
       OR current_database() IS DISTINCT FROM 'eggsor_p2b_disposable'
       OR current_user IS DISTINCT FROM 'postgres' THEN
        RAISE EXCEPTION 'Wrong disposable target or administrator';
    END IF;
    IF (SELECT shobj_description(oid, 'pg_database') FROM pg_database
        WHERE datname = current_database()) IS DISTINCT FROM
       'EGGSOR_PHASE2B_DISPOSABLE_v1' THEN
        RAISE EXCEPTION 'Disposable database marker is missing';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'eggsor_phase2b_runner')
       OR EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'eggsor_p2b_test')
       OR EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public') THEN
        RAISE EXCEPTION 'Unexpected role, test schema, or public tables: stop and inspect';
    END IF;
END;
$$;

CREATE ROLE eggsor_phase2b_runner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD NULL;
CREATE SCHEMA eggsor_p2b_test AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON SCHEMA eggsor_p2b_test FROM PUBLIC;
GRANT CONNECT ON DATABASE eggsor_p2b_disposable TO eggsor_phase2b_runner;
GRANT USAGE ON SCHEMA eggsor_p2b_test TO eggsor_phase2b_runner;

CREATE TABLE eggsor_p2b_test."user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(200) NOT NULL,
    email VARCHAR(254) UNIQUE,
    google_sub VARCHAR(255) UNIQUE,
    display_name VARCHAR(120),
    avatar_url VARCHAR(1024),
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL,
    password_set BOOLEAN NOT NULL,
    invite_token_hash VARCHAR(64),
    invite_expires_at TIMESTAMPTZ,
    password_reset_token_hash VARCHAR(64),
    password_reset_expires_at TIMESTAMPTZ
);
CREATE TABLE eggsor_p2b_test.sorting_session (
    session_ref VARCHAR(40) PRIMARY KEY,
    user_id INTEGER NULL,
    started_at TIMESTAMPTZ NULL,
    ended_at TIMESTAMPTZ NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'starting',
    CONSTRAINT ck_sorting_session_status CHECK (status IN
        ('starting', 'running', 'stopping', 'completed', 'failed',
         'interrupted', 'historical', 'unknown')),
    CONSTRAINT ck_sorting_session_time_order CHECK
        (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at),
    CONSTRAINT fk_sorting_session_user FOREIGN KEY (user_id)
        REFERENCES eggsor_p2b_test."user"(id) ON DELETE SET NULL
);
CREATE TABLE eggsor_p2b_test.egg_record (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weight_grams INTEGER NOT NULL,
    size VARCHAR(30) NOT NULL,
    quality VARCHAR(30) NOT NULL,
    confidence DOUBLE PRECISION NOT NULL,
    session_ref VARCHAR(40) NOT NULL,
    sorted_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_egg_record_sorting_session FOREIGN KEY (session_ref)
        REFERENCES eggsor_p2b_test.sorting_session(session_ref) ON DELETE RESTRICT
);
CREATE TABLE eggsor_p2b_test.audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NULL,
    event_type VARCHAR(40) NOT NULL,
    actor VARCHAR(80) NOT NULL,
    description VARCHAR(300) NOT NULL,
    event_key VARCHAR(100) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_audit_log_user FOREIGN KEY (user_id)
        REFERENCES eggsor_p2b_test."user"(id) ON DELETE SET NULL
);
CREATE TABLE eggsor_p2b_test.tray_alert (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_number INTEGER NOT NULL UNIQUE,
    egg_count INTEGER NOT NULL,
    session_ref VARCHAR(40) NOT NULL,
    is_read BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_sorting_session_user_id ON eggsor_p2b_test.sorting_session(user_id);
CREATE INDEX ix_egg_record_session_ref ON eggsor_p2b_test.egg_record(session_ref);
CREATE INDEX ix_audit_log_user_id ON eggsor_p2b_test.audit_log(user_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA eggsor_p2b_test TO eggsor_phase2b_runner;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA eggsor_p2b_test TO eggsor_phase2b_runner;
DO $$
BEGIN
    IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'eggsor_p2b_test' AND c.relkind = 'S') <> 4
       OR (SELECT count(*) FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid
           JOIN pg_namespace n ON n.oid = t.relnamespace
           WHERE n.nspname = 'eggsor_p2b_test' AND c.contype = 'f'
             AND c.convalidated) <> 3 THEN
        RAISE EXCEPTION 'Fixture identity sequences or foreign keys are incomplete';
    END IF;
END;
$$;
COMMIT;
